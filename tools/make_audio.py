"""Record French pronunciation files for every flashcard using the macOS `say` command.

Usage (from the project folder):  python3 tools/make_audio.py
Creates audio/<hash>.m4a for each entry and audio/manifest.js mapping spoken text -> file.
Existing files are reused, so rerun it after adding words to the word lists.
serve.py also imports this module to record cards added from the app.
"""
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AUDIO_DIR = ROOT / "audio"
MANIFEST = AUDIO_DIR / "manifest.js"
USER_FILE = ROOT / "words-user.js"
VOICE = "Thomas"  # France French voice that ships with macOS
RATE = "160"      # words per minute; Thomas's normal speed (lower it, e.g. "130", to slow all recordings)


def speech_text(fr, say=None):
    # Must match speechText() in app.js
    text = say or fr
    text = re.sub(r"\(.*?\)", " ", text)
    text = text.replace("…", " ")
    return re.sub(r"\s+", " ", text).strip()


def load_user_cards():
    if not USER_FILE.exists():
        return []
    match = re.search(r"addUserWords\((.*)\);", USER_FILE.read_text(encoding="utf8"), re.S)
    return json.loads(match.group(1)) if match else []


def save_user_cards(cards):
    content = ("// Your own cards, added from the app (managed by serve.py)\n"
               "addUserWords(" + json.dumps(cards, ensure_ascii=False, indent=2) + ");\n")
    tmp = USER_FILE.with_suffix(".tmp")
    tmp.write_text(content, encoding="utf8")
    tmp.replace(USER_FILE)  # atomic, so a crash never leaves a half-written file


def load_texts():
    texts = set()
    for path in sorted(ROOT.glob("words-[0-9]*.js")):
        body = path.read_text(encoding="utf8").split("`")[1]
        for line in body.strip().split("\n"):
            parts = [p.strip() for p in line.split(" = ")]
            texts.add(speech_text(parts[0], parts[3] if len(parts) > 3 else None))
    for card in load_user_cards():
        texts.add(speech_text(card["fr"], card.get("say")))
    return sorted(t for t in texts if t)


def audio_name(text):
    return hashlib.md5(text.encode("utf8")).hexdigest()[:12] + ".m4a"


def record(text):
    name = audio_name(text)
    out = AUDIO_DIR / name
    if not out.exists():
        AUDIO_DIR.mkdir(exist_ok=True)
        # `say` writes bloated m4a files, so record to AIFF and compress with afconvert
        with tempfile.TemporaryDirectory() as tmp:
            raw = Path(tmp) / "raw.aiff"
            subprocess.run(["say", "-v", VOICE, "-r", RATE, "-o", str(raw), "--", text], check=True)
            subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", "32000", str(raw), str(out)],
                           check=True)
    return text, name


def read_manifest():
    if not MANIFEST.exists():
        return {}
    match = re.search(r"const AUDIO = (.*);", MANIFEST.read_text(encoding="utf8"), re.S)
    return json.loads(match.group(1)) if match else {}


def write_manifest(manifest):
    MANIFEST.write_text(
        "// Generated by tools/make_audio.py — spoken text -> audio file\n"
        "const AUDIO = " + json.dumps(manifest, ensure_ascii=False, indent=0, sort_keys=True) + ";\n",
        encoding="utf8",
    )


def add_to_manifest(text, name):
    manifest = read_manifest()
    manifest[text] = name
    write_manifest(manifest)


def main():
    AUDIO_DIR.mkdir(exist_ok=True)
    texts = load_texts()
    with ThreadPoolExecutor(max_workers=8) as pool:
        manifest = dict(pool.map(record, texts))
    used = set(manifest.values())
    for stale in AUDIO_DIR.glob("*.m4a"):
        if stale.name not in used:
            stale.unlink()
    write_manifest(manifest)
    print(f"{len(manifest)} audio files in {AUDIO_DIR}")


if __name__ == "__main__":
    sys.exit(main())
